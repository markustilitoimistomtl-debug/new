"""Packs every .lsp file in logos/uudet-logot/ into lsp-new-logos.js, which LSP shows under Templates → New logos.
Usage: python3 tools/build_new_logos.py"""
import glob, json, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
logos = []
for fn in sorted(glob.glob(os.path.join(root, 'logos', 'uudet-logot', '*.lsp'))):
    o = json.load(open(fn, encoding='utf-8'))
    o.pop('saved', None)
    logos.append(o)
with open(os.path.join(root, 'lsp-new-logos.js'), 'w', encoding='utf-8') as f:
    f.write('/* LSP new logos: generated by tools/build_new_logos.py from logos/uudet-logot/. */\n')
    f.write('window.LSP_NEW_LOGOS=' + json.dumps(logos, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(logos), 'logos')
